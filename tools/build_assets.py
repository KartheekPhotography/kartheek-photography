"""Builds js/quote-assets.js: subset Roboto fonts + dark logo, ready to embed in the PDF.
Run: python3 tools/build_assets.py   (needs fontTools + Pillow; only for the site owner when fonts/logo change)"""
import base64, io, json, zlib, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/google-fonts/ofl/roboto/Roboto[wdth,wght].ttf'
LOGO = os.path.join(ROOT, 'src/logo/logo.png')
INK = (0x2b, 0x26, 0x22)  # logo colour on the light PDF

chars = [chr(c) for c in range(0x20, 0x7f)] + [chr(c) for c in range(0xa0, 0x180)] + list('₹–—•’‘“”…·×')
text = ''.join(chars)

fonts = {}
for key, wght in (('regular', 400), ('medium', 500), ('bold', 700)):
    vf = TTFont(SRC_FONT)
    inst = instancer.instantiateVariableFont(vf, {'wght': wght, 'wdth': 100})
    opts = subset.Options(); opts.layout_features = []; opts.name_IDs = [1, 2]; opts.notdef_outline = True
    opts.glyph_names = False; opts.hinting = False
    sub = subset.Subsetter(opts); sub.populate(text=text); sub.subset(inst)
    buf = io.BytesIO(); inst.save(buf); raw = buf.getvalue()
    f = TTFont(io.BytesIO(raw))
    upm = f['head'].unitsPerEm
    cmap = f.getBestCmap(); order = f.getGlyphOrder(); hmtx = f['hmtx']
    glyphs = {}
    for cp, gname in cmap.items():
        gid = order.index(gname)
        glyphs[cp] = [gid, round(hmtx[gname][0] * 1000 / upm)]
    os2 = f['OS/2']; hhea = f['hhea']; head = f['head']
    fonts[key] = {
        'b64': base64.b64encode(zlib.compress(raw, 9)).decode(),
        'len1': len(raw),
        'glyphs': glyphs,
        'bbox': [round(v * 1000 / upm) for v in (head.xMin, head.yMin, head.xMax, head.yMax)],
        'ascent': round(hhea.ascent * 1000 / upm), 'descent': round(hhea.descent * 1000 / upm),
        'cap': round(getattr(os2, 'sCapHeight', 700) * 1000 / upm),
        'notdefGid': 0,
    }
    print(key, len(raw), 'bytes', len(glyphs), 'glyphs')

# logo: recolour white -> INK, keep alpha; RGB + SMask as Flate streams
im = Image.open(LOGO).convert('RGBA')
w = 1400; h = round(im.height * w / im.width)
im = im.resize((w, h), Image.LANCZOS)
alpha = im.getchannel('A')
rgb = Image.new('RGB', im.size, INK)
logo = {
    'w': w, 'h': h,
    'rgb': base64.b64encode(zlib.compress(rgb.tobytes(), 9)).decode(),
    'alpha': base64.b64encode(zlib.compress(alpha.tobytes(), 9)).decode(),
}
print('logo', w, h, len(logo['rgb']) + len(logo['alpha']))

data = json.dumps({'fonts': fonts, 'logo': logo}, separators=(',', ':'))
out = ('/* AUTO-GENERATED by tools/build_assets.py. Do not edit by hand. */\n'
       '(function(r){var A=' + data + ';if(typeof module!=="undefined"&&module.exports)module.exports=A;r.QUOTE_ASSETS=A})(typeof window!=="undefined"?window:globalThis);\n')
open(os.path.join(ROOT, 'js/quote-assets.js'), 'w').write(out)
print('wrote js/quote-assets.js', len(out) // 1024, 'KB')
